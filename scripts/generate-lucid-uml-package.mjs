function stripEmptyUmlMethods(node) {
  if (Array.isArray(node)) {
    for (const item of node) stripEmptyUmlMethods(item)
    return
  }
  if (node && typeof node === 'object') {
    if (node.type === 'umlClass' && Array.isArray(node.methods) && node.methods.length === 0) {
      delete node.methods
    }
    for (const k of Object.keys(node)) stripEmptyUmlMethods(node[k])
  }
}
